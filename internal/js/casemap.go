func init() {
	// U+1F80..U+1FAF: Greek letters with ypogegrammeni or prosgegrammeni uppercase to the capital plus IOTA.
	bases := []rune{0x1F08, 0x1F28, 0x1F68}
	for blk, base := range bases {
		start := rune(0x1F80 + blk*0x10)
		for i := rune(0); i < 8; i++ {
			specialUpper[start+i] = []rune{base + i, 0x0399}
			specialUpper[start+8+i] = []rune{base + i, 0x0399}
		}
	}
}

// ToUpperCase implements String.prototype.toUpperCase.
func ToUpperCase(s string) string {
	cps := decodeWTF8(s)
	out := make([]rune, 0, len(cps))
	for _, r := range cps {
		if m, ok := specialUpper[r]; ok {
			out = append(out, m...)
			continue
		}
		if r >= 0xD800 && r <= 0xDFFF {
			out = append(out, r)
			continue
		}
		out = append(out, unicode.ToUpper(r))
	}
	return FromCodePoints(out)
}

// ToLowerCase implements String.prototype.toLowerCase, including the final sigma rule.
func ToLowerCase(s string) string {
	cps := decodeWTF8(s)
	out := make([]rune, 0, len(cps))
	for i, r := range cps {
		switch {
		case r == 0x0130:
			out = append(out, 0x69, 0x0307)
		case r == 0x03A3:
			if isFinalSigma(cps, i) {
				out = append(out, 0x03C2)
			} else {
				out = append(out, 0x03C3)
			}
		case r >= 0xD800 && r <= 0xDFFF:
			out = append(out, r)
		default:
			out = append(out, unicode.ToLower(r))
		}
	}
	return FromCodePoints(out)
}

func isCased(r rune) bool {
	return unicode.IsUpper(r) || unicode.IsLower(r) || unicode.IsTitle(r) ||
		unicode.Is(unicode.Other_Lowercase, r) || unicode.Is(unicode.Other_Uppercase, r)
}

func isCaseIgnorable(r rune) bool {
	switch r {
	case 0x27, 0x2E, 0x3A, 0x5E, 0x60, 0xA8, 0xAD, 0xAF, 0xB4, 0xB7, 0xB8, 0x0387, 0x055F, 0x05F4, 0x2018,
		0x2019, 0x2024, 0x2027, 0xFE13, 0xFE52, 0xFE55, 0xFF07, 0xFF0E, 0xFF1A:
		return true
	}
	return unicode.In(r, unicode.Mn, unicode.Me, unicode.Cf, unicode.Lm, unicode.Sk)
}

func isFinalSigma(cps []rune, i int) bool {
	before := false
	for j := i - 1; j >= 0; j-- {
		if isCaseIgnorable(cps[j]) {
			continue
		}
		before = isCased(cps[j])
		break
	}
	if !before {
		return false
	}
	for j := i + 1; j < len(cps); j++ {
		if isCaseIgnorable(cps[j]) {
			continue
		}
		return !isCased(cps[j])
	}
	return true
}
